-- YEP core schema, exactly as shown on the ER diagram.
-- The five profile tables share users.user_id as both primary key and foreign key
-- (JPA JOINED inheritance); there is deliberately no second user_id column.

CREATE TABLE users (
    user_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(120) NOT NULL,
    email         VARCHAR(190) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    status        VARCHAR(20)  NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE youth_participant (
    youth_id            BIGINT PRIMARY KEY REFERENCES users (user_id) ON DELETE CASCADE,
    age                 INTEGER,
    country             VARCHAR(80),
    digital_skills      VARCHAR(80),
    level_two_eligible  BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE facilitator (
    facilitator_id BIGINT PRIMARY KEY REFERENCES users (user_id) ON DELETE CASCADE,
    specialisation VARCHAR(190)
);

CREATE TABLE mentor (
    mentor_id    BIGINT PRIMARY KEY REFERENCES users (user_id) ON DELETE CASCADE,
    organisation VARCHAR(190),
    expertise    VARCHAR(500)
);

CREATE TABLE administrator (
    admin_id   BIGINT PRIMARY KEY REFERENCES users (user_id) ON DELETE CASCADE,
    department VARCHAR(190)
);

CREATE TABLE partner_organisation (
    partner_id        BIGINT PRIMARY KEY REFERENCES users (user_id) ON DELETE CASCADE,
    organisation_name VARCHAR(190) NOT NULL,
    country           VARCHAR(80)
);

CREATE TABLE learning_activity (
    activity_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    facilitator_id BIGINT NOT NULL REFERENCES facilitator (facilitator_id),
    partner_id     BIGINT REFERENCES partner_organisation (partner_id),
    title          VARCHAR(190) NOT NULL,
    description    VARCHAR(4000),
    start_date     DATE NOT NULL,
    category       VARCHAR(80),
    level          VARCHAR(10) NOT NULL
);

CREATE TABLE enrollment (
    enrollment_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    youth_id        BIGINT NOT NULL REFERENCES youth_participant (youth_id) ON DELETE CASCADE,
    activity_id     BIGINT NOT NULL REFERENCES learning_activity (activity_id) ON DELETE CASCADE,
    enrollment_date TIMESTAMP WITH TIME ZONE NOT NULL,
    status          VARCHAR(20) NOT NULL,
    CONSTRAINT uk_enrollment_youth_activity UNIQUE (youth_id, activity_id)
);

CREATE TABLE assessment (
    assessment_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_id     BIGINT NOT NULL REFERENCES learning_activity (activity_id) ON DELETE CASCADE,
    youth_id        BIGINT NOT NULL REFERENCES youth_participant (youth_id) ON DELETE CASCADE,
    score           INTEGER,
    feedback        VARCHAR(4000),
    assessment_date TIMESTAMP WITH TIME ZONE
);

CREATE TABLE certificate (
    certificate_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    youth_id           BIGINT NOT NULL REFERENCES youth_participant (youth_id) ON DELETE CASCADE,
    certificate_number VARCHAR(30) NOT NULL,
    issue_date         DATE NOT NULL,
    achievement        VARCHAR(500) NOT NULL,
    CONSTRAINT uk_certificate_number UNIQUE (certificate_number)
);

CREATE TABLE discussion_thread (
    thread_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_id BIGINT NOT NULL REFERENCES learning_activity (activity_id) ON DELETE CASCADE,
    topic       VARCHAR(190) NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE discussion_post (
    post_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    thread_id  BIGINT NOT NULL REFERENCES discussion_thread (thread_id) ON DELETE CASCADE,
    user_id    BIGINT NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    content    VARCHAR(4000) NOT NULL,
    posted_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE team (
    team_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mentor_id   BIGINT REFERENCES mentor (mentor_id),
    activity_id BIGINT NOT NULL REFERENCES learning_activity (activity_id) ON DELETE CASCADE,
    team_name   VARCHAR(120) NOT NULL
);

CREATE TABLE team_member (
    member_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id   BIGINT NOT NULL REFERENCES team (team_id) ON DELETE CASCADE,
    youth_id  BIGINT NOT NULL REFERENCES youth_participant (youth_id) ON DELETE CASCADE,
    role      VARCHAR(20) NOT NULL,
    CONSTRAINT uk_team_member_team_youth UNIQUE (team_id, youth_id)
);

CREATE TABLE impact_project (
    project_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id        BIGINT NOT NULL REFERENCES team (team_id) ON DELETE CASCADE,
    title          VARCHAR(190) NOT NULL,
    description    VARCHAR(6000),
    challenge_area VARCHAR(40) NOT NULL,
    status         VARCHAR(30) NOT NULL
);

CREATE TABLE milestone (
    milestone_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id   BIGINT NOT NULL REFERENCES impact_project (project_id) ON DELETE CASCADE,
    title        VARCHAR(190) NOT NULL,
    due_date     DATE,
    status       VARCHAR(20) NOT NULL
);

CREATE TABLE notification (
    notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    message         VARCHAR(1000) NOT NULL,
    date_sent       TIMESTAMP WITH TIME ZONE NOT NULL,
    type            VARCHAR(20) NOT NULL
);
