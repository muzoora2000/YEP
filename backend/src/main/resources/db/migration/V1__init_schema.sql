-- =====================================================================
--  YEP - Youth Digital Empowerment and Virtual Exchange Platform
--  V1 : baseline schema for Neon Postgres (production, run by Flyway)
--  Notes:
--   * id columns use IDENTITY so Hibernate's GenerationType.IDENTITY works
--   * every table carries created_at / updated_at
--   * enum columns are VARCHAR with the JPA @Enumerated(STRING) values
-- =====================================================================

-- ---------------------------------------------------------------------
-- users  (SINGLE_TABLE inheritance: role is also the discriminator)
-- ---------------------------------------------------------------------
CREATE TABLE users (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name           VARCHAR(120)  NOT NULL,
    email               VARCHAR(190)  NOT NULL,
    password_hash       VARCHAR(100)  NOT NULL,
    role                VARCHAR(30)   NOT NULL,
    country             VARCHAR(80),
    phone               VARCHAR(30),
    consent_given       BOOLEAN       NOT NULL,
    account_status      VARCHAR(30)   NOT NULL,
    -- Participant
    age                 INTEGER,
    skill_level         VARCHAR(30),
    -- Facilitator
    expertise_area      VARCHAR(120),
    expertise_topics    VARCHAR(400),
    sessions_facilitated INTEGER      NOT NULL DEFAULT 0,
    -- Mentor
    mentorship_areas    VARCHAR(400),
    -- Admin
    permissions         VARCHAR(500),
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE
);

CREATE UNIQUE INDEX uk_users_email      ON users (email);
CREATE INDEX        idx_users_role        ON users (role);
CREATE INDEX        idx_users_account_status ON users (account_status);
CREATE INDEX        idx_users_created_at ON users (created_at);

-- ---------------------------------------------------------------------
-- virtual_exchanges  (SINGLE_TABLE inheritance: exchange_level discriminator)
-- ---------------------------------------------------------------------
CREATE TABLE virtual_exchanges (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title              VARCHAR(180)   NOT NULL,
    description        VARCHAR(4000),
    exchange_level     VARCHAR(20)    NOT NULL,
    start_date         DATE           NOT NULL,
    end_date           DATE,
    status             VARCHAR(30)    NOT NULL,
    organiser_id       BIGINT,
    -- Level one specific
    topic              VARCHAR(50),
    max_participants   INTEGER,
    session_link       VARCHAR(500),
    facilitator_id     BIGINT,
    -- Level two specific
    focus_area         VARCHAR(50),
    max_teams          INTEGER,
    applications_open  BOOLEAN,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_virtual_exchanges_level       ON virtual_exchanges (exchange_level);
CREATE INDEX idx_virtual_exchanges_status      ON virtual_exchanges (status);
CREATE INDEX idx_virtual_exchanges_start_date  ON virtual_exchanges (start_date);

-- ---------------------------------------------------------------------
-- enrollments  (participant <-> virtual_exchange)
-- ---------------------------------------------------------------------
CREATE TABLE enrollments (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participant_id      BIGINT       NOT NULL REFERENCES users (id)              ON DELETE CASCADE,
    virtual_exchange_id BIGINT       NOT NULL REFERENCES virtual_exchanges (id)  ON DELETE CASCADE,
    enrolled_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    completion_status   VARCHAR(30)  NOT NULL,
    completed_at        TIMESTAMP WITH TIME ZONE,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE
);

CREATE UNIQUE INDEX uk_enrollments_participant_exchange ON enrollments (participant_id, virtual_exchange_id);
CREATE INDEX idx_enrollments_virtual_exchange_id ON enrollments (virtual_exchange_id);
CREATE INDEX idx_enrollments_participant_id      ON enrollments (participant_id);
CREATE INDEX idx_enrollments_completion_status   ON enrollments (completion_status);

-- ---------------------------------------------------------------------
-- teams
-- ---------------------------------------------------------------------
CREATE TABLE teams (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                   VARCHAR(120)  NOT NULL,
    description            VARCHAR(2000),
    level_two_exchange_id  BIGINT        NOT NULL REFERENCES virtual_exchanges (id) ON DELETE CASCADE,
    mentor_id              BIGINT        REFERENCES users (id) ON DELETE SET NULL,
    created_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at             TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_teams_level_two_exchange_id ON teams (level_two_exchange_id);
CREATE INDEX idx_teams_mentor_id              ON teams (mentor_id);
CREATE INDEX idx_teams_created_at             ON teams (created_at);

-- ---------------------------------------------------------------------
-- team_members
-- ---------------------------------------------------------------------
CREATE TABLE team_members (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id        BIGINT       NOT NULL REFERENCES teams (id)   ON DELETE CASCADE,
    participant_id BIGINT       NOT NULL REFERENCES users (id)   ON DELETE CASCADE,
    member_role    VARCHAR(20)  NOT NULL,
    joined_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE
);

CREATE UNIQUE INDEX uk_team_members_team_participant ON team_members (team_id, participant_id);
CREATE INDEX idx_team_members_team_id        ON team_members (team_id);
CREATE INDEX idx_team_members_participant_id ON team_members (participant_id);

-- ---------------------------------------------------------------------
-- impact_projects
-- ---------------------------------------------------------------------
CREATE TABLE impact_projects (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title               VARCHAR(180)   NOT NULL,
    problem_statement   VARCHAR(4000),
    proposed_solution   VARCHAR(4000),
    team_id             BIGINT         NOT NULL REFERENCES teams (id) ON DELETE CASCADE,
    status              VARCHAR(30)    NOT NULL,
    submission_date     TIMESTAMP WITH TIME ZONE,
    ai_assisted         BOOLEAN        NOT NULL DEFAULT FALSE,
    ai_usage_note       VARCHAR(2000),
    review_feedback     VARCHAR(4000),
    reviewed_by_id      BIGINT,
    reviewed_at         TIMESTAMP WITH TIME ZONE,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE
);

CREATE UNIQUE INDEX uk_impact_projects_team_id ON impact_projects (team_id);
CREATE INDEX idx_impact_projects_team_id ON impact_projects (team_id);
CREATE INDEX idx_impact_projects_status  ON impact_projects (status);

-- ---------------------------------------------------------------------
-- assessments  (polymorphic target: participant_target_id / team_target_id)
-- ---------------------------------------------------------------------
CREATE TABLE assessments (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_type            VARCHAR(20)   NOT NULL,
    participant_target_id  BIGINT        REFERENCES users (id) ON DELETE CASCADE,
    team_target_id         BIGINT        REFERENCES teams (id) ON DELETE CASCADE,
    assessor_id            BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    criteria               VARCHAR(200)  NOT NULL,
    score                  INTEGER       NOT NULL,
    feedback               VARCHAR(4000),
    assessment_date        TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at             TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_assessments_target CHECK (
        (target_type = 'PARTICIPANT' AND participant_target_id IS NOT NULL AND team_target_id IS NULL)
        OR (target_type = 'TEAM' AND team_target_id IS NOT NULL AND participant_target_id IS NULL)
    )
);

CREATE INDEX idx_assessments_participant_target_id ON assessments (participant_target_id);
CREATE INDEX idx_assessments_team_target_id        ON assessments (team_target_id);
CREATE INDEX idx_assessments_assessor_id           ON assessments (assessor_id);
CREATE INDEX idx_assessments_target_type           ON assessments (target_type);

-- ---------------------------------------------------------------------
-- certificates
-- ---------------------------------------------------------------------
CREATE TABLE certificates (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id                BIGINT         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    title                       VARCHAR(200)   NOT NULL,
    issue_date                  TIMESTAMP WITH TIME ZONE NOT NULL,
    verification_code           VARCHAR(64)    NOT NULL,
    related_activity_or_project VARCHAR(300),
    created_at                  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at                  TIMESTAMP WITH TIME ZONE
);

CREATE UNIQUE INDEX uk_certificates_verification_code ON certificates (verification_code);
CREATE INDEX idx_certificates_recipient_id ON certificates (recipient_id);
CREATE INDEX idx_certificates_issue_date   ON certificates (issue_date);

-- ---------------------------------------------------------------------
-- messages  (SINGLE_TABLE inheritance: message_type discriminator)
--   direct / team / system rows use the shared columns only,
--   announcement rows also use scope, published, approval columns.
-- ---------------------------------------------------------------------
CREATE TABLE messages (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id             BIGINT        REFERENCES users (id) ON DELETE SET NULL,
    recipient_id          BIGINT        REFERENCES users (id) ON DELETE CASCADE,
    team_id               BIGINT        REFERENCES teams (id) ON DELETE CASCADE,
    exchange_id           BIGINT        REFERENCES virtual_exchanges (id) ON DELETE CASCADE,
    subject               VARCHAR(200),
    body                  VARCHAR(4000) NOT NULL,
    is_read               BOOLEAN       NOT NULL DEFAULT FALSE,
    sent_at               TIMESTAMP WITH TIME ZONE NOT NULL,
    ai_generated          BOOLEAN       NOT NULL DEFAULT FALSE,
    ai_flag_reason        VARCHAR(500),
    ai_moderation_status  VARCHAR(30),
    message_type          VARCHAR(30)   NOT NULL,
    -- announcement only
    scope                 VARCHAR(30),
    published             BOOLEAN,
    requires_human_approval BOOLEAN,
    approved_by_id        BIGINT,
    approved_at           TIMESTAMP WITH TIME ZONE,
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at            TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_messages_sender_id    ON messages (sender_id);
CREATE INDEX idx_messages_recipient_id ON messages (recipient_id);
CREATE INDEX idx_messages_team_id      ON messages (team_id);
CREATE INDEX idx_messages_exchange_id  ON messages (exchange_id);
CREATE INDEX idx_messages_message_type ON messages (message_type);
