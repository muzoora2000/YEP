CREATE TABLE learning_material (
    material_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_id   BIGINT NOT NULL REFERENCES learning_activity (activity_id) ON DELETE CASCADE,
    title         VARCHAR(190) NOT NULL,
    material_type VARCHAR(20) NOT NULL,
    url           VARCHAR(1000) NOT NULL,
    description   VARCHAR(2000),
    uploaded_by   BIGINT NOT NULL REFERENCES users (user_id),
    uploaded_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    published     BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE virtual_session (
    session_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_id       BIGINT NOT NULL REFERENCES learning_activity (activity_id) ON DELETE CASCADE,
    title             VARCHAR(190) NOT NULL,
    scheduled_start   TIMESTAMP WITH TIME ZONE NOT NULL,
    duration_minutes  INTEGER NOT NULL,
    meeting_link      VARCHAR(1000) NOT NULL,
    status            VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED',
    created_by        BIGINT NOT NULL REFERENCES users (user_id)
);

CREATE TABLE attendance (
    attendance_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id    BIGINT NOT NULL REFERENCES virtual_session (session_id) ON DELETE CASCADE,
    youth_id      BIGINT NOT NULL REFERENCES youth_participant (youth_id) ON DELETE CASCADE,
    status        VARCHAR(20) NOT NULL,
    marked_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_attendance_session_youth UNIQUE (session_id, youth_id)
);


CREATE TABLE project_review (
    review_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  BIGINT NOT NULL REFERENCES impact_project (project_id) ON DELETE CASCADE,
    mentor_id   BIGINT NOT NULL REFERENCES mentor (mentor_id),
    decision    VARCHAR(30) NOT NULL,
    feedback    VARCHAR(4000) NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE project_support (
    support_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id   BIGINT NOT NULL REFERENCES impact_project (project_id) ON DELETE CASCADE,
    partner_id   BIGINT NOT NULL REFERENCES partner_organisation (partner_id) ON DELETE CASCADE,
    support_type VARCHAR(20) NOT NULL,
    message      VARCHAR(2000),
    status       VARCHAR(20) NOT NULL DEFAULT 'OFFERED',
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE opportunity (
    opportunity_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partner_id       BIGINT NOT NULL REFERENCES partner_organisation (partner_id) ON DELETE CASCADE,
    title            VARCHAR(190) NOT NULL,
    opportunity_type VARCHAR(20) NOT NULL,
    description      VARCHAR(4000),
    location         VARCHAR(190),
    deadline         DATE,
    status           VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE opportunity_interest (
    interest_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    opportunity_id BIGINT NOT NULL REFERENCES opportunity (opportunity_id) ON DELETE CASCADE,
    youth_id       BIGINT NOT NULL REFERENCES youth_participant (youth_id) ON DELETE CASCADE,
    message        VARCHAR(2000),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_opportunity_interest UNIQUE (opportunity_id, youth_id)
);

CREATE TABLE password_reset_token (
    token_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    token_hash VARCHAR(128) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    used       BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE audit_log (
    log_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT REFERENCES users (user_id) ON DELETE SET NULL,
    action     VARCHAR(80) NOT NULL,
    entity     VARCHAR(80) NOT NULL,
    entity_id  BIGINT,
    details    VARCHAR(4000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE system_setting (
    setting_key   VARCHAR(80) PRIMARY KEY,
    setting_value VARCHAR(4000) NOT NULL,
    updated_by    BIGINT REFERENCES users (user_id),
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL
);
